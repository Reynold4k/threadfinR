test_that("plot_overview writes Threadfin's own overview file, draws it and returns rasters", {
  skip_if_no_threadfin()
  res <- fixture("run")
  pdf <- tempfile(fileext = ".pdf")
  out <- plot_overview(res, file = pdf, output = "file")
  expect_identical(out, normalizePath(pdf, mustWork = FALSE))
  expect_identical(readBin(pdf, "raw", 4L), charToRaw("%PDF"))
  png <- plot_overview(res, output = "file")
  expect_true(png_magic(png))
  ras <- plot_overview(res, output = "raster")
  expect_true(inherits(ras, c("nativeRaster", "raster")))
  dev <- tempfile(fileext = ".png")
  device <- c(list(dev, width = 600, height = 450), if (isTRUE(capabilities("cairo"))) list(type = "cairo"))
  opened <- tryCatch(is.null(do.call(grDevices::png, device)), error = function(e) FALSE)
  skip_if_not(opened, "no PNG graphics device")
  shown <- plot_overview(res)
  grDevices::dev.off()
  expect_null(shown)
  expect_true(png_magic(dev))
  # an AnnData after the run draws the same figure through threadfin.pl.overview
  expect_true(png_magic(plot_overview(py_object(res)$adata, output = "file")))
})

test_that("the figure shortcuts and plot_threadfin draw Threadfin's figures", {
  skip_if_no_threadfin()
  res <- fixture("run")
  expect_true(png_magic(plot_clone_map(res, color = "n_cells", output = "file")))
  expect_true(png_magic(plot_clone_map(res, output = "file", dpi = 50)))
  expect_true(png_magic(plot_label_effects(res, output = "file")))
  expect_true(png_magic(plot_association(res, output = "file")))
  expect_true(png_magic(plot_association(res$tests$true_programme, output = "file")))
  expect_error(plot_association(res, label = "nope"), "no programme test")
  expect_error(plot_memory(res), "no clonal memory")
  mem <- quiet(clonal_memory(fixture("time")$copy(), "timepoint", n_null = 20L, n_boot = 20L, verbose = FALSE))
  expect_true(png_magic(plot_memory(mem, output = "file")))
  pa <- quiet(profile_association(fixture("time")$copy(), "true_programme", n_perm = 100L, verbose = FALSE))
  expect_true(png_magic(plot_label_effects(list(true_programme = pa), output = "file")))
  expect_true(png_magic(plot_threadfin("coherence", res, output = "file")))
  svg <- plot_threadfin("stability", res, file = tempfile(fileext = ".svg"), output = "file")
  expect_match(paste(readLines(svg, n = 5L, warn = FALSE), collapse = ""), "<svg|<\\?xml")
  expect_error(plot_threadfin("no_such_plot", res), "no function")
  expect_error(plot_threadfin(42), "name of a threadfin.pl function")
})
